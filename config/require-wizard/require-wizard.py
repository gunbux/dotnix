"""Claude Code Stop hook: block a work-repo reply that hands Chun an unsafe infra apply.

Chun applies Terraform, Terragrunt and OpenTofu changes on work infra himself, and wants each such handoff as a
wizard script (the `wizard` skill), never as raw commands pasted in the reply. A wizard may apply only through the
library's `tf_apply_reviewed`, which stops on any change outside the plan Claude reviewed (`tfplan-guard`). On
16 Nov 2026 a wizard-less dashboard apply deleted another engineer's unmerged monitors.

Every wizard handed over must also pass the wizard skill's lint.sh: the template's library unchanged, each stage
through run_stage so a failed run resumes, and no check left to the human as prose. On 17 and 18 Nov 2026 two gate
wizards could not resume, Claude finished their stages by hand, and handed over gate A's smoke script for gate B.
"""

import json
import re
import subprocess
import sys
from pathlib import Path

WORK_REPO = re.compile(r"/(repo/greptilia|worktrees/greptilia/)")
FENCE = re.compile(r"```[^\n]*\n(.*?)```", re.S)
APPLY = re.compile(r"\b(terragrunt|terraform|tofu)\b[^\n]*\b(apply|destroy)\b")
WIZARD_SCRIPT = re.compile(r"wizard[^\s`]*\.sh\b")
SCRIPT_PATH = re.compile(r"(?<![\w/.~-])((?:/|~/)[^\s`'\")\]]+\.sh)\b")
GUARDED = "tf_apply_reviewed"
TEMPLATE = Path.home() / ".claude/skills/wizard/template.sh"

REASON = (
    "This reply hands Chun raw Terraform/Terragrunt apply commands. He wants a wizard for every manual "
    "procedure: load the `wizard` skill, write the script (each apply as a confirmed stage, after the plan "
    "summary in words), run `bash -n` on it, and give him the script path and the one command to run it."
)


def last_reply(transcript: Path) -> str:
    reply = ""
    for line in transcript.read_text().splitlines():
        try:
            entry = json.loads(line)
        except json.JSONDecodeError:
            continue
        if entry.get("type") != "assistant":
            continue
        content = entry.get("message", {}).get("content", [])
        if isinstance(content, str):
            text = content
        else:
            text = "\n".join(block.get("text", "") for block in content if block.get("type") == "text")
        if text.strip():
            reply = text
    return reply


def needs_wizard(reply: str) -> bool:
    handed_over = any(APPLY.search(block) for block in FENCE.findall(reply))
    return handed_over and not WIZARD_SCRIPT.search(reply)


def function_body(lines: list[str], name: str) -> list[str]:
    start = next((i for i, line in enumerate(lines) if line.startswith(f"{name}() {{")), None)
    if start is None:
        return []
    end = next((i for i in range(start, len(lines)) if lines[i] == "}"), len(lines) - 1)
    return lines[start : end + 1]


def unguarded_applies(script: str, template: str | None) -> list[str]:
    """Each problem with how SCRIPT applies Terraform: an apply outside tf_apply_reviewed, or a changed copy of it."""
    lines = script.splitlines()
    guarded = function_body(lines, GUARDED)
    problems = [
        f"line {n}: {line.strip()}"
        for n, line in enumerate(lines, 1)
        if APPLY.search(line) and not line.lstrip().startswith("#") and line not in guarded
    ]
    if guarded and template is not None and guarded != function_body(template.splitlines(), GUARDED):
        problems.append(f"{GUARDED} differs from the wizard skill's template.sh; copy the library unchanged")
    return problems


def lint_problems(path: Path) -> list[str]:
    """lint.sh's findings for PATH when it is a wizard (it carries the template's header)."""
    lint = TEMPLATE.with_name("lint.sh")
    if "Generated by the /wizard skill" not in path.read_text() or not lint.is_file():
        return []
    run = subprocess.run(["bash", str(lint), str(path)], capture_output=True, text=True, stdin=subprocess.DEVNULL)
    return [line for line in run.stdout.splitlines() if line.strip()] if run.returncode else []


def wizard_problems(reply: str) -> list[str]:
    template = TEMPLATE.read_text() if TEMPLATE.is_file() else None
    problems = []
    for raw in sorted(set(SCRIPT_PATH.findall(reply))):
        path = Path(raw).expanduser()
        if path.is_file():
            problems += [f"{path} {p}" for p in unguarded_applies(path.read_text(), template)]
            problems += lint_problems(path)
    return problems


def main() -> None:
    hook = json.load(sys.stdin)
    if hook.get("stop_hook_active") or not WORK_REPO.search(hook.get("cwd", "")):
        return
    transcript = Path(hook.get("transcript_path", ""))
    if not transcript.is_file():
        return
    reply = last_reply(transcript)
    if needs_wizard(reply):
        print(json.dumps({"decision": "block", "reason": REASON}))
        return
    problems = wizard_problems(reply)
    if problems:
        reason = (
            "A wizard you hand over breaks the wizard skill's rules. Apply Terraform only by calling "
            f"`{GUARDED}`, with a scope file from `tfplan-guard record` on a plan you reviewed. Run every stage "
            "through `run_stage`, so a failed run resumes, and run each check in its stage. When a run fails, "
            "fix the wizard and have Chun run the same wizard again; never finish its stages by hand. Fix these, "
            "then hand the wizard over again:\n" + "\n".join(problems)
        )
        print(json.dumps({"decision": "block", "reason": reason}))


if __name__ == "__main__":
    main()
